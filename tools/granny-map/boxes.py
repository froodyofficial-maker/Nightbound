import json, sys, numpy as np
R = json.load(open(sys.argv[1])); C = R['cell']; E = R['ext']; N = R['n']
g = np.array([[c == '1' for c in row] for row in R['rows']], dtype=bool)
xc = lambda i: -E + (i + 0.5) * C
# clear the gate openings and anything outside the outer wall (|x|,|z| > 31.6: unreachable)
for gx, gz in [(-4.0, -29.9), (6.0, 30.75)]:
    for j in range(N):
        for i in range(N):
            if abs(xc(i) - gx) < 2.6 and abs(xc(j) - gz) < 1.4: g[j, i] = False
for j in range(N):
    for i in range(N):
        if abs(xc(i)) > 31.8 or abs(xc(j)) > 31.8: g[j, i] = False
# greedy rectangles
used = np.zeros_like(g); boxes = []
for j in range(N):
    i = 0
    while i < N:
        if g[j, i] and not used[j, i]:
            w = 1
            while i + w < N and g[j, i + w] and not used[j, i + w]: w += 1
            h = 1
            while j + h < N and all(g[j + h, i:i + w]) and not any(used[j + h, i:i + w]): h += 1
            used[j:j + h, i:i + w] = True
            x0, z0 = -E + i * C, -E + j * C
            boxes.append([round(x0 + w * C / 2, 3), round(z0 + h * C / 2, 3), round(w * C / 2, 3), round(h * C / 2, 3)])
            i += w
        else: i += 1
out = '// Collision for "Granny\'s House": walls and solid props of the converted Granny 3 map, rasterised\n// (0.25m cells, knee to head height) and merged into boxes [x, z, hx, hz]. Generated by tools; do not edit.\nexport const GRANNY_BOXES = ' + json.dumps(boxes, separators=(',', ':')) + ';\n'
open(sys.argv[2], 'w').write(out)
print(len(boxes), 'boxes', len(out) // 1024, 'KB')
